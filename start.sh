#!/bin/bash
cd "$(dirname "$0")"

echo "======================================================="
echo "  额度与到期管理系统 (MySQL 云端版)"
echo "======================================================="

# 检查依赖
if [ ! -d "node_modules" ]; then
  echo ">>> 正在安装运行依赖..."
  npm install
fi

# 启动服务
echo ">>> 正在启动服务器..."
node server.js
